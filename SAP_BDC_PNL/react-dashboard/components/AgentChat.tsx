"use client"

import { useState, useRef, useEffect } from "react"
import { DEMO_CONFIG } from "@/lib/demo-config"

interface Message {
  role: "user" | "assistant"
  content: string
  sqlSnippet?: string   // SQL generated by PnL_Analyst tool, if any
  isStreaming?: boolean
}

interface AgentSSEEvent {
  type?: string
  delta?: { type?: string; text?: string }
  content_block?: { type?: string; text?: string }
  tool_use?: { name?: string; input?: { query?: string } }
}

function parseSseChunk(raw: string): AgentSSEEvent | null {
  if (!raw.startsWith("data:")) return null
  const json = raw.slice(5).trim()
  if (json === "[DONE]") return { type: "done" }
  try { return JSON.parse(json) } catch { return null }
}

export function AgentChat() {
  const [messages, setMessages] = useState<Message[]>([])
  const [input, setInput] = useState("")
  const [streaming, setStreaming] = useState(false)
  const bottomRef = useRef<HTMLDivElement>(null)
  const abortRef  = useRef<AbortController | null>(null)

  useEffect(() => { bottomRef.current?.scrollIntoView({ behavior: "smooth" }) }, [messages])

  async function sendMessage(text: string) {
    if (!text.trim() || streaming) return

    const userMsg: Message = { role: "user", content: text }
    const history = [...messages, userMsg]
    setMessages([...history, { role: "assistant", content: "", isStreaming: true }])
    setInput("")
    setStreaming(true)

    const abort = new AbortController()
    abortRef.current = abort

    try {
      const res = await fetch("/api/agent", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ messages: history }),
        signal: abort.signal,
      })

      if (!res.ok) {
        const err = await res.json()
        setMessages((prev) => [
          ...prev.slice(0, -1),
          { role: "assistant", content: `Error: ${err.error ?? "Agent call failed"}` },
        ])
        return
      }

      const reader = res.body?.getReader()
      const decoder = new TextDecoder()
      let buffer = ""
      let accText = ""
      let sqlSnippet: string | undefined

      while (reader) {
        const { done, value } = await reader.read()
        if (done) break
        buffer += decoder.decode(value, { stream: true })
        const lines = buffer.split("\n")
        buffer = lines.pop() ?? ""

        for (const line of lines) {
          const evt = parseSseChunk(line)
          if (!evt) continue
          if (evt.type === "done") break

          // Text delta
          if (evt.delta?.type === "text_delta" && evt.delta.text) {
            accText += evt.delta.text
            setMessages((prev) => [
              ...prev.slice(0, -1),
              { role: "assistant", content: accText, sqlSnippet, isStreaming: true },
            ])
          }

          // Tool use — capture SQL from PnL_Analyst
          if (evt.tool_use?.name === "PnL_Analyst" && evt.tool_use.input?.query) {
            sqlSnippet = evt.tool_use.input.query
          }
        }
      }

      setMessages((prev) => [
        ...prev.slice(0, -1),
        { role: "assistant", content: accText || "(No response)", sqlSnippet, isStreaming: false },
      ])
    } catch (e: any) {
      if (e?.name === "AbortError") return
      setMessages((prev) => [
        ...prev.slice(0, -1),
        { role: "assistant", content: "Connection error — please retry." },
      ])
    } finally {
      setStreaming(false)
    }
  }

  return (
    <div className="flex flex-col h-full min-h-0">
      <h2 className="text-sm font-semibold pb-3 border-b border-border shrink-0">Ask the Agent</h2>

      {/* Messages */}
      <div className="flex-1 overflow-y-auto py-3 space-y-4 min-h-0">
        {messages.length === 0 && (
          <p className="text-xs text-muted-foreground text-center pt-4">
            Ask a question about the P&amp;L data, or pick a suggestion below.
          </p>
        )}
        {messages.map((msg, i) => (
          <div key={i} className={`flex flex-col gap-1 ${msg.role === "user" ? "items-end" : "items-start"}`}>
            <div
              className={`max-w-[92%] rounded-lg px-3 py-2 text-sm leading-relaxed ${
                msg.role === "user"
                  ? "bg-primary text-primary-foreground"
                  : "bg-muted text-foreground"
              }`}
            >
              {msg.content}
              {msg.isStreaming && <span className="inline-block w-1.5 h-3.5 bg-current ml-0.5 animate-pulse" />}
            </div>
            {/* SQL generated by PnL_Analyst tool */}
            {msg.sqlSnippet && !msg.isStreaming && (
              <details className="max-w-[92%] text-xs">
                <summary className="cursor-pointer text-muted-foreground hover:text-foreground">Generated SQL</summary>
                <pre className="mt-1 p-2 bg-muted rounded text-xs overflow-x-auto whitespace-pre-wrap break-words">
                  {msg.sqlSnippet}
                </pre>
              </details>
            )}
          </div>
        ))}
        <div ref={bottomRef} />
      </div>

      {/* Starter questions */}
      {messages.length === 0 && (
        <div className="shrink-0 pb-2 flex flex-wrap gap-1.5">
          {DEMO_CONFIG.starterQuestions.map((q) => (
            <button
              key={q}
              onClick={() => sendMessage(q)}
              className="text-xs rounded-full border border-border px-3 py-1 hover:bg-accent transition-colors truncate max-w-full"
            >
              {q}
            </button>
          ))}
        </div>
      )}

      {/* Input */}
      <div className="shrink-0 flex gap-2 pt-3 border-t border-border">
        <input
          value={input}
          onChange={(e) => setInput(e.target.value)}
          onKeyDown={(e) => e.key === "Enter" && !e.shiftKey && sendMessage(input)}
          placeholder="Ask a question…"
          className="flex-1 rounded-md border border-border bg-background px-3 py-2 text-sm focus:outline-none focus:ring-2 focus:ring-ring"
          disabled={streaming}
        />
        <button
          onClick={() => sendMessage(input)}
          disabled={streaming || !input.trim()}
          className="rounded-md bg-primary px-4 py-2 text-sm font-medium text-primary-foreground disabled:opacity-40 transition-opacity"
        >
          {streaming ? "…" : "Send"}
        </button>
      </div>
    </div>
  )
}
