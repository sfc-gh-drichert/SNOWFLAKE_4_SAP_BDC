-- =============================================================================
-- teardown.sql — Drop all World Delivery ESG demo objects
--
-- Safe to run multiple times. Drops objects in reverse dependency order.
-- Does NOT drop the database or warehouse — those may be shared with
-- other demos or modules.
--
-- Variables: <% db_name %>, <% wh_name %>
-- =============================================================================

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE IDENTIFIER('<% wh_name %>');
USE DATABASE IDENTIFIER('<% db_name %>');
USE SCHEMA ESG;

-- Agent
DROP AGENT IF EXISTS WORLD_DELIVERY_ESG_AGENT;

-- Semantic View
DROP SEMANTIC VIEW IF EXISTS WORLD_DELIVERY_ESG_SV;

-- Streamlit
DROP STREAMLIT IF EXISTS WORLD_DELIVERY_ESG_DASHBOARD;
DROP STAGE IF EXISTS WORLD_DELIVERY_ESG_STG;

-- Analytics Views
DROP VIEW IF EXISTS V_DECARB_LEVER_ANALYSIS;
DROP VIEW IF EXISTS V_EMISSION_FORECAST;
DROP VIEW IF EXISTS V_ESG_KPI_DASHBOARD;
DROP VIEW IF EXISTS V_GOGREEN_REVENUE;
DROP VIEW IF EXISTS V_DECARB_PROGRESS;
DROP VIEW IF EXISTS V_ESRS_E1_DISCLOSURE;
DROP VIEW IF EXISTS V_GHG_EMISSIONS_SUMMARY;

-- Marketplace / external
DROP TABLE IF EXISTS EXT_CLIMATE_RISK;
DROP TABLE IF EXISTS EXT_ESG_SCORES;
DROP TABLE IF EXISTS EXT_EMISSION_FACTORS;

-- SuccessFactors
DROP TABLE IF EXISTS SF_HEALTH_SAFETY;
DROP TABLE IF EXISTS SF_CORE_WORKFORCE;

-- Custom CDS ESG tables
DROP TABLE IF EXISTS Z_DECARB_LEVERS;
DROP TABLE IF EXISTS Z_EMISSION_FORECAST;
DROP TABLE IF EXISTS Z_GOGREEN_PLUS_ORDER;
DROP TABLE IF EXISTS Z_FLEET_FUEL_LOG;
DROP TABLE IF EXISTS Z_FLEET_VEHICLE;
DROP TABLE IF EXISTS Z_FACILITY_ENERGY;
DROP TABLE IF EXISTS Z_SHIPMENT_EMISSIONS;

-- BDC master data
DROP TABLE IF EXISTS GENERALLEDGERACCOUNTLINEITEM;
DROP TABLE IF EXISTS PLANT;
DROP TABLE IF EXISTS COSTCENTER;
DROP TABLE IF EXISTS COMPANYCODE;

-- Schema (only if empty — fails safely if other objects exist)
DROP SCHEMA IF EXISTS ESG;

SELECT 'Teardown complete. Database and warehouse preserved.' AS status;
